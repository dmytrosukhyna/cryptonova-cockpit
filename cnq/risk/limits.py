"""Лимиты риск-слоя демо-счетов (20.10.2026, владелец: портфельный риск — дневной стоп, просадка, плечо, концентрация,
корреляция, аварийный выключатель, защита от устаревших данных). Только демо: реальные деньги этот модуль не трогает.

Все числа — здесь, одним списком, чтобы их было видно и легко поменять. Файлы — в data/ рабочей папки движка
(/opt/cnq/run/data на сервере); CNQ_RISK_DIR меняет папку (тесты)."""
from __future__ import annotations

import os

# ── СТОП новых входов (HALT) ─────────────────────────────────────────────────────────────────────────────────────────────
DAILY_LOSS_HALT = -0.03     # результат всех демо-счетов вместе за день UTC ≤ −3 % → стоп новых входов до следующего дня UTC
DRAWDOWN_HALT = -0.15       # просадка всех демо-счетов вместе от пика ≤ −15 % → стоп, пока владелец не сбросит (cli: risk reset)
DATA_MAX_AGE_MIN = 10.0     # рыночные данные старше 10 минут → блок всех входов (цены могли уйти, сигнал считался по старому)

# ── блоки отдельных входов ───────────────────────────────────────────────────────────────────────────────────────────────
LEVERAGE_MAX = 3.0          # плечо счёта = брутто открытых позиций / капитал счёта; вход, после которого стало бы > 3×, — блок
COIN_MAX = 0.25             # одна монета > 25 % брутто всех счетов → блок входов в эту монету
CLUSTER_MAX = 0.50          # кластер похожих монет > 50 % брутто (по чистой позиции: лонг и шорт гасят друг друга) → блок
CLUSTER_RHO = 0.80          # «похожие» = корреляция дневных доходностей за 30 дней выше 0.8 у каждой пары внутри кластера
CORR_DAYS = 30              # окно корреляции, дней
# Знаменатель долей монеты и кластера — брутто всех счетов, но не меньше их общего капитала: пока счета почти пустые, одна
# сделка была бы «100 % брутто» и блокировала бы саму себя (на 20.10 брутто ≈ 0.3 капитала; BTC ×2 одного счёта дал бы > 50 %).

WARN_AT = 0.70              # предупреждение (WARN), когда любой показатель дошёл до 70 % своего лимита

# ── сам риск-слой ────────────────────────────────────────────────────────────────────────────────────────────────────────
STATE_MAX_AGE_MIN = 10.0    # состояние риск-слоя старше 10 минут → блок всех входов (риск-слой не работает — не торгуем вслепую)
REPLAY_H = 6.0              # время входа дальше 6 ч от часов сервера (тесты, прогоны истории) — шлюз не применяется

# Зеркальные счета: свои входы не делают, повторяют чужие с множителем. Вход базового стола проверяется и за зеркало
# (иначе зеркало ×4 обходило бы лимит плеча). Множитель = cnq/agents/turbo_desk.LST_K (тест сверяет).
MIRRORS = {"lst": (("lstx", 4.0),)}


def risk_dir() -> str:
    return os.environ.get("CNQ_RISK_DIR", "data")


def path(name: str, base: str | None = None) -> str:
    return os.path.join(base or risk_dir(), name)


KILL_FILE = "kill_switch.json"         # аварийный выключатель (cli: kill on|off|status)
STATE_FILE = "risk_state.json"         # полное состояние риск-слоя (пишет шаг risk каждую минуту)
CONVEYOR_FILE = "conveyor_state.json"  # стадии стратегий от конвейера: {"desks": {key: {stage, paused, reason_ru}}}
